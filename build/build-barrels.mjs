// Generate a per-framework barrel (index) that re-exports every compiled
// component, so apps can `import { CrSwitch } from "@control-room/design-system/react"`
// instead of reaching into .../components/CrSwitch. Runs after `mitosis build`;
// the dist/frameworks/** tree is a git-ignored build artifact, so these barrels
// are regenerated on every compile (CI included). --check fails on drift.
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const FRAMEWORKS = join(ROOT, "dist", "frameworks");

// target → { ext: component-file extension, index: barrel filename }
const TARGETS = {
  react:   { ext: "tsx",    index: "index.ts" },
  vue:     { ext: "vue",    index: "index.ts" },
  svelte:  { ext: "svelte", index: "index.js" },
  angular: { ext: "js",     index: "index.ts" },
  solid:   { ext: "jsx",    index: "index.jsx" },
};

const check = process.argv.includes("--check");
const HEADER =
  "// GENERATED by build/build-barrels.mjs — do not edit. Re-run `npm run build:components`.\n";

let drift = false;

for (const [target, { ext, index }] of Object.entries(TARGETS)) {
  const dir = join(FRAMEWORKS, target);
  const compDir = join(dir, "components");
  if (!existsSync(compDir)) {
    if (check) continue; // nothing compiled yet — not a drift condition
    console.warn(`⚠ ${target}: no components/ dir — run 'mitosis build' first`);
    continue;
  }
  const names = readdirSync(compDir)
    .filter((f) => f.endsWith("." + ext))
    .map((f) => f.slice(0, -(ext.length + 1)))
    .sort();

  const lines = names.map((name) => {
    // Angular emits `export default class` + a named `<Name>Module`; re-export both.
    if (target === "angular") {
      return `export { default as ${name}, ${name}Module } from "./components/${name}.${ext}";`;
    }
    return `export { default as ${name} } from "./components/${name}.${ext}";`;
  });

  const body = HEADER + lines.join("\n") + "\n";
  const outFile = join(dir, index);

  if (check) {
    const current = existsSync(outFile) ? readFileSync(outFile, "utf8") : "";
    if (current !== body) {
      drift = true;
      console.error(`  - ${target}/${index}: stale (run 'npm run build:components')`);
    }
  } else {
    writeFileSync(outFile, body);
    console.log(`wrote dist/frameworks/${target}/${index}  (${names.length} components)`);
  }
}

if (check) {
  if (drift) {
    console.error("\n✗ framework barrels are stale");
    process.exit(1);
  }
  console.log("✓ framework barrels are in sync");
}

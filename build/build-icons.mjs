#!/usr/bin/env node
/**
 * Build the alternate "pixel" icon pack from Iconify (pixelarticons) — the softer,
 * pixel-art escape hatch for CrIcon. The house "cr" set stays the hand-authored,
 * geometric-glyph identity default (Design Language — geometric-glyph iconography);
 * this generates a second pack, keyed by the SAME icon names, that a theme/app can
 * opt into via <CrIcon set="pixel" />.
 *
 * Offline + tree-shakable: icon path data is baked into lib/icons/pixel.js at build
 * time (no runtime Iconify fetch). Pixelarticons are single <path fill=currentColor>
 * on a 24×24 grid — same viewBox as the house set — so they render through CrIcon's
 * portable single-<path> model on all six targets (no innerHTML; Vue/Solid safe).
 *
 * `--check` fails if lib/icons/pixel.ts is stale. Run in the build chain.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "lib", "icons", "pixel.ts");
const CHECK = process.argv.includes("--check");

// house icon name → pixelarticons name. Kept in sync with the CR set in CrIcon.
const NAME_MAP = {
  play: "play",
  pause: "pause",
  stop: "debug-stop",
  retry: "reload",
  deploy: "cloud-upload",
  scan: "scale",
  search: "search",
  alert: "alert",
  error: "close-box",
  done: "check",
  clock: "clock",
  cpu: "cpu",
  logs: "list",
  filter: "filter",
  sliders: "sliders-2",
  close: "close",
  chevron: "chevron-down",
  plus: "plus",
  minus: "minus",
  trash: "trash",
  external: "external-link",
  copy: "copy",
  session: "user",
  menu: "menu",
};

const data = require("@iconify-json/pixelarticons/icons.json");
const aliases = data.aliases || {};
const resolve = (name) => data.icons[name] || (aliases[name] && data.icons[aliases[name].parent]);

const pack = {};
const missing = [];
for (const [cr, px] of Object.entries(NAME_MAP)) {
  const icon = resolve(px);
  if (!icon) {
    missing.push(`${cr} → ${px}`);
    continue;
  }
  // pixelarticons bodies are a single <path d="…" fill="currentColor"/>. Extract
  // every d and join (defensive if a body ever has more than one path).
  const ds = [...icon.body.matchAll(/d="([^"]+)"/g)].map((m) => m[1]);
  if (!ds.length) {
    missing.push(`${cr} → ${px} (no path)`);
    continue;
  }
  pack[cr] = ds.join(" ");
}

if (missing.length) {
  console.warn(`build-icons: ${missing.length} unresolved pixel icon(s): ${missing.join(", ")}`);
}

const version = JSON.parse(
  readFileSync(join(ROOT, "node_modules/@iconify-json/pixelarticons/package.json"), "utf8")
).version;

const out =
  `// GENERATED by build/build-icons.mjs from @iconify-json/pixelarticons@${version} — do not edit.\n` +
  `// The soft/pixel escape-hatch pack for CrIcon (set="pixel"). 24×24, fill=currentColor.\n` +
  `// Regenerate: npm run build:icons\n` +
  `export const PIXEL_ICONS: Record<string, string> = ${JSON.stringify(pack, null, 2)};\n`;

if (CHECK) {
  const cur = existsSync(OUT) ? readFileSync(OUT, "utf8") : null;
  if (cur !== out) {
    console.error("✗ lib/icons/pixel.ts is stale — run `npm run build:icons`");
    process.exit(1);
  }
  console.log(`✓ pixel icon pack up to date (${Object.keys(pack).length} icons)`);
  process.exit(0);
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, out);
console.log(
  `wrote lib/icons/pixel.js (${Object.keys(pack).length} icons from pixelarticons@${version})`
);
